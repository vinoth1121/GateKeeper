#!/usr/bin/env python3
"""Generate BENCHMARKS.md from the k6 run artifacts in results/.

Every number in the generated report is sourced from results/*.json and
results/machine.json. Runs that were never performed are reported as
"NOT RUN" -- never as zero, never fabricated.

Usage (from anywhere):
    python scripts/generate_benchmarks.py
"""
import json
import os
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS_DIR = os.path.join(ROOT, "results")
OUTPUT_PATH = os.path.join(ROOT, "BENCHMARKS.md")

K6_RUNS = ["steady", "ramp", "connections"]
PCT_FIELD = {"p50": "med", "p95": "p(95)", "p99": "p(99)"}


def load_json(name):
    path = os.path.join(RESULTS_DIR, name)
    if not os.path.isfile(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, json.JSONDecodeError) as exc:
        print("warning: could not read {}: {}".format(path, exc), file=sys.stderr)
        return None


def k6_value(data, metric, field):
    try:
        return data["metrics"][metric]["values"][field]
    except (KeyError, TypeError):
        return None


def fmt(value, decimals=2):
    if value is None:
        return "NOT RUN"
    return "{:.{d}f}".format(float(value), d=decimals)


def fmt_int(value):
    if value is None:
        return "NOT RUN"
    return "{:,.0f}".format(float(value))


def fmt_pct(value):
    if value is None:
        return "NOT RUN"
    return "{:.2f}%".format(float(value) * 100)


def run_row(name, data):
    if data is None:
        return "| {} | NOT RUN | NOT RUN | NOT RUN | NOT RUN | NOT RUN | NOT RUN |".format(name)
    return "| {} | {} | {} | {} | {} | {} | {} |".format(
        name,
        fmt_int(k6_value(data, "http_reqs", "count")),
        fmt_int(k6_value(data, "http_reqs", "rate")),
        fmt(k6_value(data, "http_req_duration", PCT_FIELD["p50"])),
        fmt(k6_value(data, "http_req_duration", PCT_FIELD["p95"])),
        fmt(k6_value(data, "http_req_duration", PCT_FIELD["p99"])),
        fmt_pct(k6_value(data, "http_req_failed", "rate")),
    )


def overhead_rows(data):
    labels = [
        ("direct_ms", "direct (mock upstream)"),
        ("via_ms", "via gateway"),
        ("delta_ms", "delta (gateway overhead)"),
    ]
    rows = []
    for key, label in labels:
        if data is None:
            rows.append("| {} | NOT RUN | NOT RUN | NOT RUN |".format(label))
            continue
        section = data.get(key)
        if not isinstance(section, dict):
            rows.append("| {} | NOT RUN | NOT RUN | NOT RUN |".format(label))
            continue
        rows.append("| {} | {} | {} | {} |".format(
            label,
            fmt(section.get("p50")),
            fmt(section.get("p95")),
            fmt(section.get("p99")),
        ))
    return "\n".join(rows)


def burst_row(data):
    if data is None:
        return "| burst (free tier, 50 requests) | NOT RUN | NOT RUN |"
    return "| burst (free tier, 50 requests) | {} | {} |".format(
        fmt_int(k6_value(data, "http_reqs", "count")),
        fmt_pct(k6_value(data, "checks", "rate")),
    )


def machine_line(machine):
    if machine is None:
        return "NOT RUN — results/machine.json is missing (run scripts/run_load.ps1 to collect it)."
    return "{} — CPU: {} ({} logical cores) — RAM: {}".format(
        machine.get("os", "unknown"),
        machine.get("cpu", "unknown"),
        machine.get("cores", "unknown"),
        machine.get("memory", "unknown"),
    )


def main():
    rows = "\n".join(run_row(name, load_json(name + ".json")) for name in K6_RUNS)
    overhead = load_json("overhead.json")
    burst = load_json("burst.json")
    machine = load_json("machine.json")
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    markdown = """# GateKeeper Benchmarks

> Generated by `scripts/generate_benchmarks.py` on {generated}.
>
> Evidence policy: every number below is read from `results/*.json` produced by
> the k6 scripts in `loadtest/` (see `results/README.md`). Runs that were not
> performed are shown as **NOT RUN** — nothing here is hand-typed, estimated,
> or zero-filled.

## Machine

{machine}

## Load runs

| Run | Requests | RPS (avg) | p50 (ms) | p95 (ms) | p99 (ms) | Error rate |
|---|---|---|---|---|---|---|
{rows}

## Gateway overhead (overhead.js — 300 rps per scenario, 30 s)

| Path | p50 (ms) | p95 (ms) | p99 (ms) |
|---|---|---|---|
{overhead}

## Free-tier burst validation (burst.js)

| Run | Requests | Checks passed |
|---|---|---|
{burst}

To refresh this report, re-run the load suite (`scripts/run_load.ps1`) and then
`python scripts/generate_benchmarks.py`.
""".format(generated=generated, machine=machine_line(machine), rows=rows,
            overhead=overhead_rows(overhead), burst=burst_row(burst))

    with open(OUTPUT_PATH, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(markdown)
    print("wrote {}".format(OUTPUT_PATH))


if __name__ == "__main__":
    main()